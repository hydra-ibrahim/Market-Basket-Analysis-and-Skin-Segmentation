-- Repository. https://doi.org/10.24432/C5BW33 (CC BY 4.0). See README 'Datasets' and
-- 'Data preparation' sections for full attribution and methodology.
--
-- Build steps (see README for the runnable code this was generated from):
--   1. Clean Itemname (strip runs of 2+ spaces entirely, strip '.' and '*' characters);
--      convert Price commas to decimal points.
--   2. Drop rows with a null BillNo; drop invoices whose BillNo contains 'C' (cancelled).
--   3. Drop rows where Price <= 0 or Quantity <= 0; drop rows with a null Itemname.
--   4. Filter to Country = 'United Kingdom'.
--   5. Exclude 15 non-product line items that survive the above (shipping/fee/voucher
--      entries, not products): POSTAGE, DOTCOM POSTAGE, CARRIAGE, Next Day Carriage,
--      Manual, SAMPLES, Bank Charges, AMAZON FEE, Adjust bad debt, and 6 Dotcomgiftshop
--      Gift Voucher denominations.
--   6. Group by Itemname; sum Quantity; take the MODE (most frequent) Price per item --
--      NOT a mean or quantity-weighted average (verified against the live app's actual
--      displayed prices; mode was the only aggregation that matched exactly).
--
-- Final row count: 3981 items.
--
-- Column types match AprioriAPI/models.py exactly: name is the primary key
-- (CharField(primary_key=True)), quantity is unsigned (PositiveIntegerField),
-- price is DECIMAL(6,2) (DecimalField(max_digits=6, decimal_places=2)).

